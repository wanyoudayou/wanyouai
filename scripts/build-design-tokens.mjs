import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = JSON.parse(
  readFileSync(new URL("../src/styles/tokens.json", import.meta.url), "utf8"),
);
const block = (selector, values) =>
  `${selector} {\n${Object.entries(values)
    .map(([name, value]) => {
      if (
        !/^[a-z][a-z0-9-]*$/i.test(name) ||
        typeof value !== "string" ||
        /[{};\n]/.test(value)
      )
        throw new Error(`Invalid design token: ${name}`);
      return `  --${name}: ${value};`;
    })
    .join("\n")}\n}`;
const css = `/* Generated by npm run tokens:build. Edit tokens.json. */\n${block(":root", { ...source.shared, ...source.themes.light })}\n\n${block(".dark", source.themes.dark)}\n\n/* System fallback also applies before JavaScript or when storage is unavailable. */\n@media (prefers-color-scheme: dark) {\n${block(":root:not(.light):not(.dark)", source.themes.dark)}\n}\n`;
const output = new URL("../src/styles/tokens.css", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== css)
    throw new Error("Design tokens drifted. Run npm run tokens:build.");
  console.log("Design tokens match the source.");
} else {
  writeFileSync(output, css);
  console.log(`Generated ${fileURLToPath(output)}`);
}
