-- Existing complete V1 -> constrained runtime functions and extensions namespace.
-- Transactional and data preserving. Reviewed against the current complete V1 schema.
begin;

do $version_guard$
declare current_version text;
begin
  if current_setting('server_version_num')::integer < 170000 then
    raise exception 'This candidate requires PostgreSQL 17 or later; review PostgreSQL 15 compatibility first.';
  end if;
  if to_regclass('public.app_schema_version') is not null then
    execute 'select version from public.app_schema_version where id=1' into current_version;
    if current_version > '20260928124423' then
      raise exception 'A newer application schema is installed; refusing a downgrade.';
    end if;
  end if;
end $version_guard$;

-- Future application tables must be opt-in for Data API roles, regardless of
-- the hosted project's initial default privileges.
alter default privileges for role postgres in schema public
  revoke all on tables from anon, authenticated, service_role;

create schema if not exists extensions;
grant usage on schema extensions to anon, authenticated, service_role;
do $extension$
begin
  if not exists(select 1 from pg_extension where extname='vector') then
    raise exception 'Complete V1 database required: vector extension is missing.';
  end if;
  if (select n.nspname from pg_extension e join pg_namespace n on n.oid=e.extnamespace where e.extname='vector') <> 'extensions' then
    alter extension vector set schema extensions;
  end if;
end;
$extension$;

create or replace function public.match_chunks(p_embedding extensions.vector(1024), p_limit integer default 12)
returns table (chunk_id bigint, article_id bigint, series_id bigint, access text, chunk_type text, chunk_no integer, content text, distance float)
language sql stable security invoker set search_path = '' as $$
  select c.id, c.article_id, c.series_id, c.access, c.chunk_type, c.chunk_no, c.content,
         (c.embedding operator(extensions.<=>) p_embedding)::float
  from public.article_chunks c
  join public.articles a on a.id = c.article_id
  where c.embedding is not null and a.status in ('published', 'paused')
  order by c.embedding operator(extensions.<=>) p_embedding
  limit greatest(1, least(coalesce(p_limit, 12), 24))
$$;
revoke all on function public.match_chunks(extensions.vector,integer) from public, anon, authenticated;
grant execute on function public.match_chunks(extensions.vector,integer) to service_role;

create or replace function public.is_owner() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles where id = auth.uid() and is_owner);
$$;
-- RLS policies and the explicit owner-status RPC need this scalar predicate.
revoke all on function public.is_owner() from public;
grant execute on function public.is_owner() to anon, authenticated, service_role;

alter function public.set_updated_at() set search_path = '';
revoke all on function public.handle_new_user() from public, anon, authenticated, service_role;
revoke all on function public.set_updated_at() from public, anon, authenticated, service_role;

-- Dashboard-managed automatic RLS is platform code, not an application RPC.
do $platform$
begin
  if exists(select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname='rls_auto_enable'
    and p.prorettype='pg_catalog.event_trigger'::regtype and p.pronargs=0) then
    execute 'revoke all on function public.rls_auto_enable() from public, anon, authenticated, service_role';
  end if;
end;
$platform$;


-- Application version is writable only by the migration executor, never by API roles.
create table if not exists public.app_schema_version (
  id integer primary key default 1 check (id=1),
  version text not null check (version ~ '^[0-9]{14}$'),
  applied_at timestamptz not null default now()
);
alter table public.app_schema_version enable row level security;
drop policy if exists app_schema_version_service_read on public.app_schema_version;
create policy app_schema_version_service_read on public.app_schema_version for select to service_role using (true);
revoke all on public.app_schema_version from public, anon, authenticated, service_role;
grant select on public.app_schema_version to service_role;
insert into public.app_schema_version(id,version) values(1,'20260928124423')
on conflict(id) do update set version=excluded.version, applied_at=now();

